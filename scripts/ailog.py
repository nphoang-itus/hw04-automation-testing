#!/usr/bin/env python3
"""Regenerate docs/ai/prompt-log.md (verbatim prompts + AI text output) from Claude Code transcripts.

Idempotent: rebuilds the whole file from every session of this project, so it can run after each turn.
A prompt starting with "[chore]" is a trivial task the student said needs no audit -> skipped.
Usage: python3 scripts/ailog.py
"""
import glob, json, os, re
from datetime import datetime, timedelta, timezone

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PROJ = os.path.expanduser("~/.claude/projects/" + ROOT.replace("/", "-"))
OUT = os.path.join(ROOT, "docs", "ai", "prompt-log.md")
TZ = timezone(timedelta(hours=7), "ICT")
SKIP = ("<command-", "<local-command", "<system-reminder", "Caveat:", "[Request interrupted", "[chore]")

HEADER = """# Prompt log — HW04-AI (Appendix)

**Declaration:** *I use AI tools for the following tasks,* as logged below. Tool: **Claude Code** (Anthropic).

> Each entry: tool/model, real date-time (ICT, UTC+7), **verbatim prompt**, **verbatim AI text output**, files the AI wrote/edited.
> Auto-generated by `python3 scripts/ailog.py` (rebuilt from the session transcripts; do not edit by hand).
> Verdicts, reasoning and student fixes live in `docs/ai-audit-report.md`.

## Log
"""


def text_of(content):
    if isinstance(content, str):
        return content
    return "\n".join(c.get("text", "") for c in content if c.get("type") == "text")


def load(path):
    turns, cur, ask = [], None, set()
    for line in open(path, encoding="utf-8"):
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        if d.get("type") not in ("user", "assistant") or d.get("isMeta"):
            continue
        msg, content = d.get("message", {}), d.get("message", {}).get("content")
        when = datetime.fromisoformat(d["timestamp"].replace("Z", "+00:00")).astimezone(TZ)
        if d["type"] == "user":
            if isinstance(content, list) and any(c.get("type") == "tool_result" for c in content):
                for c in content:
                    if c.get("type") == "tool_result" and c.get("tool_use_id") in ask and cur:
                        r = c.get("content")
                        r = r if isinstance(r, str) else text_of(r)
                        cur["answers"].append(r.replace("The user answered: ", "").split(" Read the answers carefully")[0])
                continue
            t = text_of(content).strip()
            m = re.search(r"<command-name>(.*?)</command-name>", t)
            if m:
                a = re.search(r"<command-args>(.*?)</command-args>", t, re.S)
                t = (m.group(1) + " " + (a.group(1).strip() if a else "")).strip()
            elif not t or t.startswith(SKIP):
                cur = None if t.startswith("[chore]") else cur
                continue
            cur = {"time": when, "prompt": t, "out": [], "answers": [], "files": [], "model": None}
            turns.append(cur)
        elif cur is not None:
            cur["model"] = cur["model"] or msg.get("model")
            for c in content or []:
                if c.get("type") == "text" and c.get("text", "").strip():
                    cur["out"].append(c["text"].strip())
                elif c.get("type") == "tool_use":
                    n, i = c.get("name"), c.get("input", {})
                    if n == "AskUserQuestion":
                        ask.add(c.get("id"))
                        cur["out"].append("**[Question to user]**\n" + "\n".join("- " + q.get("question", "") for q in i.get("questions", [])))
                    elif n in ("Write", "Edit", "NotebookEdit") and i.get("file_path"):
                        fp = i["file_path"]
                        rel = os.path.relpath(fp, ROOT) if fp.startswith(ROOT) else fp.replace(os.path.expanduser("~"), "~")
                        if rel not in cur["files"]:
                            cur["files"].append(rel)
    return turns


def fence(s):
    return "````text\n" + s + "\n````"


def main():
    turns = []
    for f in sorted(glob.glob(os.path.join(PROJ, "*.jsonl")), key=os.path.getmtime):
        turns += load(f)
    turns = [t for t in turns if t["out"] or t["files"]]  # drop local slash commands (/chrome...) with no AI output
    turns.sort(key=lambda t: t["time"])
    out = [HEADER]
    for n, t in enumerate(turns, 1):
        out.append(f"### #{n} — {t['time'].strftime('%Y-%m-%d %H:%M')} (ICT)")
        out.append(f"- **Tool / model:** Claude Code · `{t['model'] or 'unknown'}`")
        out.append("- **Prompt (verbatim):**\n" + fence(t["prompt"]))
        if t["answers"]:
            out.append("- **My answers to AI questions:**\n" + fence("\n".join(t["answers"])))
        out.append("- **Output (verbatim, text only):**\n" + fence("\n\n".join(t["out"]) or "(no text)"))
        if t["files"]:
            out.append("- **Files written/edited by AI:** " + ", ".join(f"`{x}`" for x in t["files"]))
        out.append("\n---\n")
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"Wrote {len(turns)} turns -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
